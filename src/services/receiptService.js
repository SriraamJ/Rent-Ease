export const generateMonthlyReport = (reportData, month) => {
  const doc = new jsPDF();

  // Header
  doc.setFillColor(37, 99, 235);
  doc.rect(0, 0, 210, 35, "F");

  doc.setTextColor(255, 255, 255);
  doc.setFontSize(20);
  doc.text("MONTHLY REPORT", 105, 15, { align: "center" });

  const monthName = new Date(month + "-01").toLocaleDateString("en-IN", {
    month: "long",
    year: "numeric",
  });
  doc.setFontSize(12);
  doc.text(monthName, 105, 25, { align: "center" });

  doc.setTextColor(0, 0, 0);

  // Summary
  doc.setFontSize(14);
  doc.setFont(undefined, "bold");
  doc.text("Summary", 20, 50);

  doc.setFont(undefined, "normal");
  doc.setFontSize(10);

  const summaryData = [
  ["Total Properties", reportData.totalProperties.toString()],
  ["Occupancy Rate", `${reportData.occupancyRate.toFixed(1)}%`],
  ["Expected Revenue", formatINR(reportData.expectedRevenue)],
  ["Collected Revenue", formatINR(reportData.collectedRevenue)],
  ["Collection Rate", `${reportData.collectionRate.toFixed(1)}%`],
  ["Total Expenses", formatINR(reportData.totalExpenses)],
  ["Net Income", formatINR(reportData.netIncome)],
];

autoTable(doc, {
  startY: 60,
  body: summaryData,
  theme: "plain",
  styles: { fontSize: 10, cellPadding: 3 },
  columnStyles: {
    0: { fontStyle: "bold", cellWidth: 80 },
    1: { halign: "right", cellWidth: 80 },
  },
});


  const filename = `Report_${month}.pdf`;
  doc.save(filename);

  return { success: true, filename };
};
